/* for_1.c —— 打印九九乘法表
 * 练习点：
 *   1. for 循环的基本结构：for (初始化; 条件; 步进)
 *   2. 双重循环：外层控制"第几行"，内层控制"这一行输出几项"
 *   3. printf 的左对齐输出：%-4d
 */
#include <stdio.h>

int main()
{
    int i = 0;   /* 外层循环：行号，从第 1 行到第 9 行 */
    int j = 0;   /* 内层循环：每行的列，从 1 到当前行号 */

    for (i = 1; i <= 9; i++)
    {
        for (j = 1; j <= i; j++)
        {
            printf("%d*%d=%-4d", j, i, i * j);  /* %-4d：占 4 格左边对齐，多列对得整齐 */
        }
        printf("\n");   /* 每打完一行换行 */
    }

    return 0;
}
